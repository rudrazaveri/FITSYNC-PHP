<?php
/**
 * FitSync AI — Automated MySQL -> Supabase PostgreSQL Schema & Data Migrator
 * Reads authoritative live MySQL schema (fitsync_db), converts to PostgreSQL 17 DDL,
 * creates all tables, indexes, and foreign keys in Supabase, and copies existing rows.
 */

declare(strict_types=1);

require_once __DIR__ . '/../config/bootstrap.php';

$mysql = new PDO('mysql:host=127.0.0.1;dbname=fitsync_db;charset=utf8mb4', 'root', '', [
    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION
]);

$url = $_ENV['SUPABASE_DATABASE_URL'] ?? getenv('SUPABASE_DATABASE_URL') ?: '';
$p = parse_url($url);
$dsn = sprintf(
    'pgsql:host=%s;port=%d;dbname=%s;sslmode=require',
    $p['host'] ?? '',
    $p['port'] ?? 6543,
    ltrim($p['path'] ?? '/postgres', '/')
);
$pg = new PDO($dsn, urldecode($p['user'] ?? 'postgres'), urldecode($p['pass'] ?? ''), [
    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
    PDO::ATTR_EMULATE_PREPARES => true
]);

$tables = $mysql->query("SHOW TABLES")->fetchAll(PDO::FETCH_COLUMN);
echo "Found " . count($tables) . " MySQL tables.\n";

$pgSqlDump = "-- FitSync AI PostgreSQL 17 Schema (Generated from fitsync_db)\n\n";
$fkStatements = [];
$idxStatements = [];

foreach ($tables as $table) {
    $cols = $mysql->query("SHOW COLUMNS FROM `{$table}`")->fetchAll(PDO::FETCH_ASSOC);
    $indexes = $mysql->query("SHOW INDEX FROM `{$table}`")->fetchAll(PDO::FETCH_ASSOC);

    $pkCols = [];
    $uniqGroups = [];
    $mulGroups = [];
    foreach ($indexes as $idx) {
        $kn = $idx['Key_name'];
        if ($kn === 'PRIMARY') {
            $pkCols[(int)$idx['Seq_in_index']] = $idx['Column_name'];
        } elseif ((int)$idx['Non_unique'] === 0) {
            $uniqGroups[$kn][(int)$idx['Seq_in_index']] = $idx['Column_name'];
        } else {
            $mulGroups[$kn][(int)$idx['Seq_in_index']] = $idx['Column_name'];
        }
    }
    ksort($pkCols);

    $colDefs = [];
    $hasAutoInc = false;
    $autoIncCol = null;

    foreach ($cols as $c) {
        $name = $c['Field'];
        $rawType = strtolower($c['Type']);
        $extra = strtolower($c['Extra'] ?? '');
        $isAuto = str_contains($extra, 'auto_increment');
        $nullable = $c['Null'] === 'YES';
        $default = $c['Default'];

        if ($isAuto) {
            $hasAutoInc = true;
            $autoIncCol = $name;
        }

        // Map MySQL type -> PostgreSQL type
        if (str_starts_with($rawType, 'bigint')) {
            $pgType = $isAuto ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY' : 'BIGINT';
        } elseif (str_starts_with($rawType, 'tinyint(1)')) {
            $pgType = 'SMALLINT';
        } elseif (preg_match('/^(tinyint|smallint|mediumint|int)/', $rawType)) {
            $pgType = $isAuto ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY' : 'INTEGER';
        } elseif (preg_match('/^decimal\((\d+,\d+)\)/', $rawType, $m)) {
            $pgType = "NUMERIC({$m[1]})";
        } elseif (preg_match('/^varchar\((\d+)\)/', $rawType, $m)) {
            $pgType = "VARCHAR({$m[1]})";
        } elseif (preg_match('/^char\((\d+)\)/', $rawType, $m)) {
            $pgType = "CHAR({$m[1]})";
        } elseif (preg_match('/^enum\((.+)\)$/', $rawType, $m)) {
            $pgType = "VARCHAR(60)";
        } elseif (str_contains($rawType, 'text')) {
            $pgType = 'TEXT';
        } elseif ($rawType === 'datetime' || $rawType === 'timestamp') {
            $pgType = 'TIMESTAMP';
        } elseif ($rawType === 'date') {
            $pgType = 'DATE';
        } elseif ($rawType === 'time') {
            $pgType = 'TIME';
        } elseif (str_contains($rawType, 'json')) {
            $pgType = 'JSONB';
        } else {
            $pgType = 'TEXT';
        }

        $def = "\"{$name}\" {$pgType}";
        if (!$nullable) {
            $def .= " NOT NULL";
        }
        if ($default !== null && !$isAuto) {
            if (stripos($default, 'current_timestamp') !== false) {
                $def .= " DEFAULT CURRENT_TIMESTAMP";
            } elseif (is_numeric($default) && (str_contains($pgType, 'INT') || str_contains($pgType, 'NUMERIC') || $pgType === 'SMALLINT')) {
                $def .= " DEFAULT {$default}";
            } else {
                $escaped = str_replace("'", "''", (string)$default);
                $def .= " DEFAULT '{$escaped}'";
            }
        }
        $colDefs[] = $def;
    }

    if (!empty($pkCols)) {
        $pkQuoted = implode(', ', array_map(fn($c) => "\"{$c}\"", $pkCols));
        $colDefs[] = "PRIMARY KEY ({$pkQuoted})";
    }

    foreach ($uniqGroups as $kn => $uCols) {
        ksort($uCols);
        $uQuoted = implode(', ', array_map(fn($c) => "\"{$c}\"", $uCols));
        $colDefs[] = "CONSTRAINT \"uq_{$table}_{$kn}\" UNIQUE ({$uQuoted})";
    }

    $createSql = "CREATE TABLE IF NOT EXISTS \"{$table}\" (\n  " . implode(",\n  ", $colDefs) . "\n)";
    $pgSqlDump .= $createSql . ";\n\n";
    $pg->exec($createSql);

    foreach ($mulGroups as $kn => $mCols) {
        ksort($mCols);
        $mQuoted = implode(', ', array_map(fn($c) => "\"{$c}\"", $mCols));
        $idxStatements[] = "CREATE INDEX IF NOT EXISTS \"idx_{$table}_{$kn}\" ON \"{$table}\" ({$mQuoted})";
    }

    $fks = $mysql->query("
        SELECT kcu.CONSTRAINT_NAME, kcu.COLUMN_NAME, kcu.REFERENCED_TABLE_NAME, kcu.REFERENCED_COLUMN_NAME,
               rc.DELETE_RULE, rc.UPDATE_RULE
        FROM information_schema.KEY_COLUMN_USAGE kcu
        INNER JOIN information_schema.REFERENTIAL_CONSTRAINTS rc
            ON rc.CONSTRAINT_SCHEMA = kcu.TABLE_SCHEMA AND rc.CONSTRAINT_NAME = kcu.CONSTRAINT_NAME
        WHERE kcu.TABLE_SCHEMA = 'fitsync_db' AND kcu.TABLE_NAME = '{$table}' AND kcu.REFERENCED_TABLE_NAME IS NOT NULL
    ")->fetchAll(PDO::FETCH_ASSOC);

    foreach ($fks as $fk) {
        $onDel = strtoupper($fk['DELETE_RULE'] ?? 'NO ACTION');
        if (!in_array($onDel, ['CASCADE', 'SET NULL', 'RESTRICT', 'NO ACTION'], true)) $onDel = 'NO ACTION';
        $fkName = "fk_{$table}_{$fk['CONSTRAINT_NAME']}";
        $fkStatements[] = [
            'name' => $fkName,
            'table' => $table,
            'sql' => "ALTER TABLE \"{$table}\" ADD CONSTRAINT \"{$fkName}\" FOREIGN KEY (\"{$fk['COLUMN_NAME']}\") REFERENCES \"{$fk['REFERENCED_TABLE_NAME']}\" (\"{$fk['REFERENCED_COLUMN_NAME']}\") ON DELETE {$onDel}"
        ];
    }
}

foreach ($idxStatements as $idxSql) {
    $pgSqlDump .= $idxSql . ";\n";
    $pg->exec($idxSql);
}

echo "Created all " . count($tables) . " tables and " . count($idxStatements) . " indexes in Supabase Postgres.\n";

// Copy existing data cleanly (disable triggers/FKs during bulk load by loading before adding FKs)
$copiedTables = 0;
$copiedRows = 0;
foreach ($tables as $table) {
    $existingCount = (int)$pg->query("SELECT COUNT(*) FROM \"{$table}\"")->fetchColumn();
    if ($existingCount > 0) continue;

    $rows = $mysql->query("SELECT * FROM `{$table}`")->fetchAll(PDO::FETCH_ASSOC);
    if (empty($rows)) continue;

    $cols = array_keys($rows[0]);
    $colList = implode(', ', array_map(fn($c) => "\"{$c}\"", $cols));
    $placeholders = implode(', ', array_fill(0, count($cols), '?'));
    $ins = $pg->prepare("INSERT INTO \"{$table}\" ({$colList}) VALUES ({$placeholders}) ON CONFLICT DO NOTHING");

    $pg->beginTransaction();
    foreach ($rows as $r) {
        $ins->execute(array_values($r));
        $copiedRows++;
    }
    $pg->commit();
    $copiedTables++;

    // Sync identity sequence if id column exists
    if (in_array('id', $cols, true)) {
        try {
            $pg->exec("SELECT setval(pg_get_serial_sequence('\"{$table}\"', 'id'), COALESCE((SELECT MAX(id) FROM \"{$table}\"), 1), true)");
        } catch (Throwable $e) {
            // Table without serial/identity on id
        }
    }
}

echo "Copied {$copiedRows} rows across {$copiedTables} tables.\n";

// Add Foreign Keys idempotently
$fkAdded = 0;
foreach ($fkStatements as $fk) {
    $chk = $pg->prepare("SELECT COUNT(*) FROM information_schema.table_constraints WHERE table_schema = 'public' AND table_name = ? AND constraint_name = ?");
    $chk->execute([$fk['table'], $fk['name']]);
    if ((int)$chk->fetchColumn() === 0) {
        try {
            $pg->exec($fk['sql']);
            $pgSqlDump .= $fk['sql'] . ";\n";
            $fkAdded++;
        } catch (Throwable $e) {
            echo "FK warning ({$fk['name']}): " . $e->getMessage() . "\n";
        }
    }
}

file_put_contents(__DIR__ . '/../database/fitsync_supabase_postgres_schema.sql', $pgSqlDump);
echo "Added {$fkAdded} foreign key constraints and saved database/fitsync_supabase_postgres_schema.sql.\n";
